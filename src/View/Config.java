    private void cargarDatosUsuario() {
        UsuarioController usuarioController = UsuarioController.getInstance();

        if (usuarioController != null && usuarioController.getUsuarioLogeado() != null) {
            this.usuario = usuarioController.getUsuarioLogeado();

            // Cargar datos en los labels del panel de visualización
            primerNombre.setText(usuario.getPrimerNombre());

            if (usuario.getSegundoNombre() != null && !usuario.getSegundoNombre().isEmpty()) {
                segundoNombre.setText(usuario.getSegundoNombre());
            } else {
                segundoNombre.setText("No especificado");
            }

            primerApellido.setText(usuario.getPrimerApellido());
            segundoApellido.setText(usuario.getSegundoApellido());
            correo.setText(usuario.getEmail());
            cedula.setText(usuario.getCedula());

            // Cargar datos en los textfields del panel de edición
            txtPrimerNombre.setText(usuario.getPrimerNombre());
            txtSegundoNombre.setText(usuario.getSegundoNombre() != null ? usuario.getSegundoNombre() : "");
            txtPrimerApellido.setText(usuario.getPrimerApellido());
            txtSegundoApellido.setText(usuario.getSegundoApellido());
            txtEmail.setText(usuario.getEmail());
            cedulaField.setText(usuario.getCedula());

            // Hacer el campo de cédula no editable
            cedulaField.setEditable(false);

        } else {
            JOptionPane.showMessageDialog(this, "No hay usuario logeado. Por favor, inicie sesión primero.", "Error", JOptionPane.ERROR_MESSAGE);
            this.dispose();
        }
    }

