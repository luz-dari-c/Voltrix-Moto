    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        UsuarioController usuarioController = UsuarioController.getInstance();

        if (usuarioController != null && usuarioController.getUsuarioLogeado() != null) {
            // Obtener los valores de los campos
            String primerNombre = txtPrimerNombre.getText().trim();
            String segundoNombre = txtSegundoNombre.getText().trim();
            String primerApellido = txtPrimerApellido.getText().trim();
            String segundoApellido = txtSegundoApellido.getText().trim();
            String email = txtEmail.getText().trim();

            // Llamar al controlador para actualizar
            String resultado = usuarioController.actualizarInformacionUsuario(
                    primerNombre,
                    segundoNombre,
                    primerApellido,
                    segundoApellido,
                    email
            );

            if (resultado.equals("OK")) {
                JOptionPane.showMessageDialog(this, "Información actualizada correctamente");
                cargarDatosUsuario(); // Recargar datos en los labels
            } else {
                JOptionPane.showMessageDialog(this, resultado, "Error", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "No hay usuario logeado", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

